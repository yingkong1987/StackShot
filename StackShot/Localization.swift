    private static let languageOverrideKey = "StackShotLanguageOverride"

    static func tr(_ key: String) -> String {
        #if DEBUG
        validateCoverageIfNeeded()
        #endif

        let locale = resolvedLocaleCode()
        if let value = localizedValue(for: key, locale: locale) {
            return value
        }

        if let fallbackLocale = fallbackLocale(for: locale),
           let fallbackValue = localizedValue(for: key, locale: fallbackLocale) {
            return fallbackValue
        }

        return localizedValue(for: key, locale: "en-US") ?? key
    }

    static func currentSelectionCode() -> String {
        let override = UserDefaults.standard.string(forKey: languageOverrideKey) ?? ""
        if supportedAppStoreLocales.contains(override) {
            return override
        }
        return systemPreferredLocaleCode()
    }

    static func updateSelectionCode(_ selectionCode: String) {
        if selectionCode == systemPreferredLocaleCode() {
            UserDefaults.standard.removeObject(forKey: languageOverrideKey)
        } else if supportedAppStoreLocales.contains(selectionCode) {
            UserDefaults.standard.set(selectionCode, forKey: languageOverrideKey)
        }
    }

    static func displayLanguageName(for selectionCode: String) -> String {
        if let short = shortLanguageDisplayName[selectionCode] {
            return short
        }

        let locale = Locale(identifier: selectionCode)
        let languageCode = locale.language.languageCode?.identifier
            ?? selectionCode.split(separator: "-").first.map(String.init)
            ?? selectionCode

        if let languageName = locale.localizedString(forLanguageCode: languageCode) {
            return languageName.capitalized(with: locale)
        }

        return selectionCode
    }

    static func systemPreferredLocaleCode() -> String {
        guard let preferred = Locale.preferredLanguages.first else { return "en-US" }
        let normalized = preferred.replacingOccurrences(of: "_", with: "-")

        if normalized.hasPrefix("zh-Hans") || normalized == "zh-CN" { return "zh-Hans" }
        if normalized.hasPrefix("zh-Hant") || normalized == "zh-TW" || normalized == "zh-HK" { return "zh-Hant" }

        if supportedAppStoreLocales.contains(normalized) {
            return normalized
        }

        let lang = normalized.split(separator: "-").first.map(String.init) ?? "en"
        return languageFallbackLocale[lang] ?? "en-US"
    }

    static func pickerOrderedLocaleCodes() -> [String] {
        let system = systemPreferredLocaleCode()
        return [system] + supportedAppStoreLocales.filter { $0 != system }
    }

    static func languageSettingTitle() -> String {
        tr("settings.language.title")
    }

    static func languagePickerWidth() -> CGFloat {
        languagePickerWidthCache
    }

    private static func resolvedLocaleCode() -> String {
        if let override = UserDefaults.standard.string(forKey: languageOverrideKey),
           !override.isEmpty,
           supportedAppStoreLocales.contains(override) {
            return override
        }
        return systemPreferredLocaleCode()
    }

    private static let languageFallbackLocale: [String: String] = [
        "ar": "ar", "bn": "bn", "ca": "ca", "zh": "zh-Hans", "hr": "hr", "cs": "cs", "da": "da", "nl": "nl",
        "en": "en-US", "fi": "fi", "fr": "fr", "de": "de", "el": "el", "gu": "gu", "he": "he", "hi": "hi",
